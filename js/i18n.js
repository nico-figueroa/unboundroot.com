export function initI18n() {
  const switcher = document.getElementById('language-switcher');
  if (!switcher) return;

  const buttons = switcher.querySelectorAll('button[data-lang]');
  const storedLang = window.localStorage.getItem('siteLanguage');
  applyLanguage(storedLang && translations[storedLang] ? storedLang : 'en');

  buttons.forEach((button) => {
    button.addEventListener('click', (event) => {
      event.preventDefault();
      const selected = button.getAttribute('data-lang');
      if (selected) applyLanguage(selected);
    });
  });

  const trigger = switcher.querySelector('[data-language-trigger]');
  const menu = switcher.querySelector('.language-menu');
  const closeMenu = () => {
    if (!menu || !trigger) return;
    menu.hidden = true;
    trigger.setAttribute('aria-expanded', 'false');
  };

  trigger?.addEventListener('click', () => {
    if (!menu) return;
    menu.hidden = !menu.hidden;
    trigger.setAttribute('aria-expanded', String(!menu.hidden));
  });

  switcher.addEventListener('click', (event) => {
    if (event.target.closest('[data-lang]')) closeMenu();
  });

  document.addEventListener('click', (event) => {
    if (!switcher.contains(event.target)) closeMenu();
  });

  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && !menu?.hidden) {
      closeMenu();
      trigger?.focus();
    }
  });

  document.addEventListener('i18n:refresh', () => {
    applyLanguage(window.localStorage.getItem('siteLanguage') || 'en');
  });
}

function applyLanguage(lang) {
  if (!translations[lang]) lang = 'en';
  window.localStorage.setItem('siteLanguage', lang);
  document.documentElement.lang = lang === 'es' ? 'es-CR' : 'en';

  document.querySelectorAll('[data-i18n]').forEach((node) => {
    if (node.hasAttribute('data-i18n-attr')) return;
    const value = translate(lang, node.getAttribute('data-i18n'));
    if (value !== null) node.textContent = value;
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
    const value = translate(lang, node.getAttribute('data-i18n-placeholder'));
    if (value !== null) node.setAttribute('placeholder', value);
  });

  document.querySelectorAll('[data-i18n-value]').forEach((node) => {
    const value = translate(lang, node.getAttribute('data-i18n-value'));
    if (value === null) return;
    if (node.tagName.toLowerCase() === 'input') node.value = value;
    else node.textContent = value;
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((node) => {
    const attr = node.getAttribute('data-i18n-attr');
    const value = translate(lang, node.getAttribute('data-i18n'));
    if (attr && value !== null) node.setAttribute(attr, value);
  });

  document.querySelectorAll('[data-lang]').forEach((button) => {
    const selected = button.getAttribute('data-lang') === lang;
    button.classList.toggle('active', selected);
    if (button.tagName.toLowerCase() === 'button') {
      button.setAttribute('aria-pressed', String(selected));
    }
  });

  const switcher = document.getElementById('language-switcher');
  const currentFlag = switcher?.querySelector('[data-current-flag]');
  const currentLanguage = switcher?.querySelector('[data-current-language]');
  if (currentFlag) {
    currentFlag.classList.toggle('flag--us', lang === 'en');
    currentFlag.classList.toggle('flag--cr', lang === 'es');
  }
  if (currentLanguage) currentLanguage.textContent = lang === 'es' ? 'Español' : 'English';
}

function translate(lang, key) {
  if (!key) return null;
  if (Object.hasOwn(translations[lang], key)) return translations[lang][key];
  return translations.en[key] ?? null;
}
